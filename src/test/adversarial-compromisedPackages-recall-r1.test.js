describe('edge cases the spec does not pin down', () => {
  // The spec does not say whether the same compromised package listed in two
  // buckets yields one finding or two. It must yield at least one.
  it('flags a package that is compromised in both dependencies and devDependencies at least once', () => {
    const findings = scan(
      one(
        'package.json',
        manifest({
          dependencies: { axios: '1.14.1' },
          devDependencies: { axios: '1.14.1' },
        })
      )
    );
    expect(hitsFor(findings, 'axios').length).toBeGreaterThanOrEqual(1);
  });

  // The spec does not define behavior for unparseable manifests. A static
  // browser probe must at minimum not throw and must return an array.
  it('does not throw on a malformed package.json', () => {
    const broken = '{ "name": "ledger-sync", "dependencies": { "axios": "1.14.1", } }';
    let findings;
    expect(() => {
      findings = scan(one('package.json', broken));
    }).not.toThrow();
    expect(Array.isArray(findings)).toBe(true);
  });

  // npm alias specs ("npm:axios@1.14.1" under another name) are not covered
  // by the spec. Whatever the verdict, the probe must not crash on them.
  it('does not throw on an npm alias spec pointing at a compromised version', () => {
    let findings;
    expect(() => {
      findings = scan(
        one('package.json', manifest({ dependencies: { 'http-shim': 'npm:axios@1.14.1' } }))
      );
    }).not.toThrow();
    expect(Array.isArray(findings)).toBe(true);
  });

  // Prerelease-anchored ranges are not addressed by the spec. The probe must
  // at minimum survive them without throwing.
  it('does not throw on a prerelease-anchored range for a listed package', () => {
    let findings;
    expect(() => {
      findings = scan(one('package.json', manifest({ dependencies: { axios: '^1.14.0-beta.1' } })));
    }).not.toThrow();
    expect(Array.isArray(findings)).toBe(true);
  });
});
