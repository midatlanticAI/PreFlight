describe('probeCompromisedPackages — package-lock.json v7+ packages format', () => {
  it('detects a transitive compromised version and marks it "(transitive via ...)" naming the chain', () => {
    const findings = scan([
      { path: 'package.json', content: rootManifestWithIntermediate },
      { path: 'package-lock.json', content: npmLockV3Transitive },
    ]);
    const hits = hitsFor(findings, 'axios');
    expect(hits.length).toBeGreaterThanOrEqual(1);
    expect(hits[0].title).toMatch(/transitive via/i);
    expect(hits[0].title).toContain('left-util');
  });

  it('attributes the lockfile hit to package-lock.json', () => {
    const findings = scan([
      { path: 'package.json', content: rootManifestWithIntermediate },
      { path: 'package-lock.json', content: npmLockV3Transitive },
    ]);
    const hits = hitsFor(findings, 'axios');
    expect(hits.length).toBeGreaterThanOrEqual(1);
    expect(hits[0].file).toContain('package-lock.json');
  });

  it('stays silent on a packages-format lockfile that resolved a clean version', () => {
    const cleanLock = JSON.stringify(
      {
        name: 'ledger-sync',
        version: '1.0.0',
        lockfileVersion: 3,
        packages: {
          '': { name: 'ledger-sync', version: '1.0.0', dependencies: { axios: '^1.7.0' } },
          'node_modules/axios': {
            version: '1.7.2',
            resolved: 'https://registry.npmjs.org/axios/-/axios-1.7.2.tgz',
            integrity: 'sha512-Kb7yEfPzR0dWnGtoJ9qLcVh',
          },
        },
      },
      null,
      2
    );
    const findings = scan([
      { path: 'package.json', content: manifest({ dependencies: { axios: '^1.7.0' } }) },
      { path: 'package-lock.json', content: cleanLock },
    ]);
    // The lockfile pins 1.7.2 (clean); no compromised-version finding for it.
    const lockHits = hitsFor(findings, 'axios').filter((f) => f.file.includes('package-lock.json'));
    expect(lockHits).toHaveLength(0);
  });
});

