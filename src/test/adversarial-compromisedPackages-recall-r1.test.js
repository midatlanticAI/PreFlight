// Adversarial RECALL tests for probeCompromisedPackages — round 1.
//
// Written from the shipped spec (src/learn/patterns/package-json-supply-chain.md)
// and the documented public threat-intel anchors. Deliberately NOT derived from
// the probe implementation, the threat-intel manifest, or any existing test.
//
// Anchors relied on (documented behavior):
//   axios 1.14.1 and 0.30.4 known-compromised; 1.7.2 clean
//   @tanstack/react-router 1.169.5 and 1.169.8 compromised; 1.169.9 clean
//   @bitwarden/cli 2026.4.0 compromised
//   plain-crypto-js compromised at EVERY version
//
// Documented probe behaviors under test:
//   - direct deps across dependencies / devDependencies / peerDependencies /
//     optionalDependencies / overrides / resolutions
//   - SemVer-aware range matching (ranges containing a bad version flag,
//     ranges excluding it do not)
//   - floating specs (latest / * / empty) on packages with a known-bad
//     version flag at high severity
//   - all-versions packages flag at critical for any spec
//   - transitive detection through package-lock.json (v7+ packages format and
//     legacy dependencies format), yarn.lock, pnpm-lock.yaml (v9), bun.lock,
//     with "(transitive via ...)" in the title

import { describe, it, expect } from 'vitest';
import { probeCompromisedPackages } from '../lib/probes.js';

const SEVERITIES = ['critical', 'high', 'medium', 'low', 'info'];

const manifest = (fields) =>
  JSON.stringify({ name: 'ledger-sync', version: '1.0.0', ...fields }, null, 2);

const one = (path, content) => [{ path, content }];

const scan = (files) => probeCompromisedPackages(files);

const hitsFor = (findings, pkgName) =>
  findings.filter(
    (f) =>
      (f.title && f.title.includes(pkgName)) || (f.evidence && String(f.evidence).includes(pkgName))
  );

