describe('probeCompromisedPackages — floating specs on packages with a known-bad version', () => {
  it('flags "latest" on axios at high severity', () => {
    const findings = scan(one('package.json', manifest({ dependencies: { axios: 'latest' } })));
    const hits = hitsFor(findings, 'axios');
    expect(hits.length).toBeGreaterThanOrEqual(1);
    expect(hits[0].severity).toBe('high');
  });

  it('flags "*" on axios at high severity', () => {
    const findings = scan(one('package.json', manifest({ dependencies: { axios: '*' } })));
    const hits = hitsFor(findings, 'axios');
    expect(hits.length).toBeGreaterThanOrEqual(1);
    expect(hits[0].severity).toBe('high');
  });

  it('flags an empty spec on axios at high severity', () => {
    const findings = scan(one('package.json', manifest({ dependencies: { axios: '' } })));
    const hits = hitsFor(findings, 'axios');
    expect(hits.length).toBeGreaterThanOrEqual(1);
    expect(hits[0].severity).toBe('high');
  });

  it('flags "latest" on @bitwarden/cli (package with a known-bad version)', () => {
    const findings = scan(
      one('package.json', manifest({ devDependencies: { '@bitwarden/cli': 'latest' } }))
    );
    expect(hitsFor(findings, '@bitwarden/cli').length).toBeGreaterThanOrEqual(1);
  });

  // Spec scopes the floating-spec rule to "packages with a known-bad version".
  // react has no documented compromised version, so this probe stays silent
  // (the general floating-version warning belongs to the Package.json probe).
  it('does not flag "*" on a package with no known-bad versions (react)', () => {
    const findings = scan(one('package.json', manifest({ dependencies: { react: '*' } })));
    expect(hitsFor(findings, 'react')).toHaveLength(0);
  });
});

